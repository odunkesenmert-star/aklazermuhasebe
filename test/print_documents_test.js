const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { JSDOM } = require('jsdom');
const html = fs.readFileSync('index.html', 'utf8').replace(/<script\b[^>]*>[\s\S]*?<\/script>/gi, '');
(async () => {
    const dom = new JSDOM(html, { url: 'http://print-test.local', runScripts: 'dangerously', pretendToBeVisual: true });
    const w = dom.window;
    w.alert = message => { throw new Error(message); };
    w.console.warn = () => {};
    const script = w.document.createElement('script');
    script.textContent = fs.readFileSync('app.js', 'utf8');
    w.document.body.appendChild(script);
    await new Promise(resolve => setTimeout(resolve, 100));
    w.eval(`db = createEmptyDatabase();
        db.ayarlar = {firmaAdi:'AK LAZER Fiber Lazer Kesimleri',telefon:'0344 555 01 01',adres:'Küçük Sanayi Sitesi, Dulkadiroğlu / KAHRAMANMARAŞ'};
        db.cariler = [{id:1,kodu:'C-001',adi:'Atlas Makine Sanayi',tel:'0212 555 01 01',bakiye:5040}];
        db.isEmirleri = [{id:2,orderNo:'EMR-000001',customerId:1,customerName:'Atlas Makine Sanayi',description:'KAFES KESİMİ',tarih:'14.09.2026',durum:'Teslim Edildi',subTotalBeforeDiscount:4200,discountAmount:0,discountPercent:0,subTotal:4200,tax:840,taxRate:20,total:5040}];
        db.faturalar = [{id:3,faturaNo:'FTR-2026-0001',orderId:2,cariId:1,firma:'Atlas Makine Sanayi',tur:'kesilen',tarih:'14.09.2026',vadeTarihi:'21.09.2026',tutar:5040,odemeDurumu:'odenmedi'}];
        db.personeller = [{id:4,ad:'Örnek Personel',gorev:'Lazer Operatörü',maas:30000,maasTipi:'aylik'}];
        db.personelPuantajlari = [{id:5,personelId:4,donem:'2026-09',geldiGun:26,izinGun:4,eksikGun:0,mesaiSaat:0,odendi:false}];
    `);
    function capture(name) {
        const source = w.document.querySelector('.print-preview-frame').srcdoc;
        if (process.env.PRINT_QA_DIR) {
            fs.mkdirSync(process.env.PRINT_QA_DIR, {recursive:true});
            const base = 'file://' + process.cwd() + '/';
            fs.writeFileSync(path.join(process.env.PRINT_QA_DIR, name + '.html'), source.replace(/<base href="[^"]*">/, `<base href="${base}">`));
        }
        return new JSDOM(source).window.document;
    }
    w.eval('db = validateAndNormalizeDB(db)');
    const before = w.eval('JSON.stringify(db)');
    w.printInvoiceDocument(3);
    let doc = capture('invoice');
    assert.equal(doc.querySelectorAll('.service-lines thead th').length, 3);
    assert.equal(doc.querySelectorAll('.totals-panel tr').length, 3, 'No zero-discount or duplicate gross/rate rows');
    assert.equal((doc.body.textContent.match(/EMR-000001/g) || []).length, 1, 'Linked reference appears once');
    assert.equal((doc.body.textContent.match(/5.040,00/g) || []).length, 1, 'Grand total appears once');
    assert(doc.body.textContent.includes('Resmî fatura yerine geçmez'));
    assert(!doc.body.textContent.includes('Belge Niteliği') && !doc.body.textContent.includes('İskonto'));
    w.printOrderStatement(2); capture('order');
    w.printAccountStatement(1);
    doc = capture('account');
    assert(!doc.querySelector('.metric-strip'));
    assert(doc.querySelector('.statement-table thead').textContent.includes('TAHSİLAT'));
    assert(!doc.body.textContent.includes('Eksi bakiye'));
    assert(doc.querySelector('.print-payment-footer').textContent.includes('TR04 0001 0090 1065 8664 4050 01'));
    assert(doc.querySelector('.print-payment-footer').textContent.includes('MERT ODUNKESEN'));
    assert(doc.querySelector('style').textContent.includes('@bottom-center'));
    assert.equal(doc.querySelectorAll('.statement-totals').length, 1);
    assert(doc.querySelector('.statement-totals').textContent.includes('5.040,00'));
    w.printQuoteDocument(w.eval('({...db.isEmirleri[0],islemTipi:"lazer",operationCost:4200,minutes:60,rate:70})'));
    doc = capture('quote');
    assert(!doc.querySelector('.bank-details'));
    assert.equal(doc.querySelectorAll('.totals-panel tr').length, 3);
    assert(doc.body.textContent.includes('15 gün geçerlidir'));
    w.printPayrollStatement('payroll-5');
    doc = capture('payroll');
    assert(!doc.querySelector('.metric-strip'));
    assert(!doc.body.textContent.includes('Eksik Gün Kesintisi'));
    assert(!doc.querySelector('.print-payment-footer'), 'Payroll must not request customer payment');
    assert.equal(w.eval('JSON.stringify(db)'), before, 'Printing must never mutate financial records');
    w.eval(`Object.assign(db.isEmirleri[0],{discountPercent:10,discountAmount:420,subTotal:3780,tax:756,total:4536});`);
    w.eval(`Object.assign(db.faturalar[0],{tutar:4536,matrah:3780,kdvTutari:756,kdvOrani:20,discountAmount:420,discountPercent:10}); delete db.faturalar[0].documentSnapshot; db=validateAndNormalizeDB(db);`);
    w.printInvoiceDocument(3);
    doc = capture('invoice-discount');
    assert.equal(doc.querySelectorAll('.totals-panel tr').length, 4);
    assert(doc.body.textContent.includes('İskonto (%10)'));
    assert(doc.body.textContent.includes('4.536,00'));
    w.eval(`db.isEmirleri[0].description = '<img src=x onerror=alert(1)> ' + 'Uzun açıklama ve özel üretim parçası. '.repeat(30);
        db.faturalar[0].firma = 'Çok Uzun Müşteri Unvanı Sanayi ve Ticaret Limited Şirketi';`);
    w.eval(`db.faturalar[0].aciklama=db.isEmirleri[0].description; delete db.faturalar[0].documentSnapshot; db=validateAndNormalizeDB(db);`);
    w.printInvoiceDocument(3);
    doc = capture('invoice-long');
    assert(!doc.querySelector('.service-lines img'), 'Descriptions must be escaped');
    assert(doc.querySelector('.service-lines').textContent.includes('<img src=x'));
    w.eval(`db.faturalar[0]={id:3,tur:'alinan',faturaNo:'ALS-2026-1',firma:'Tedarikçi',tarih:'14.09.2026',tutar:100,kdvOrani:0};`);
    w.printInvoiceDocument(3);
    doc = capture('purchase');
    assert(!doc.body.textContent.includes('bulunmuyor'));
    assert(!doc.querySelector('.document-reference'));
    assert(!doc.querySelector('.print-payment-footer'), 'Supplier records must not show our collection account');
    assert(doc.body.textContent.includes('KDV (%0)'));
    assert(doc.body.textContent.includes('alış faturasının bilgi dökümü'));
    w.eval(`db.isEmirleri=[]; db.islemler=Array.from({length:90},(_,i)=>({id:100+i,cariId:1,firma:'Atlas Makine Sanayi',tarih:'14.09.2026 10:00',tutar:100,isGelir:true,tip:'Tahsilat (Gelen)',aciklama:'Banka havalesi '+(i+1)}));`);
    w.printAccountStatement(1); doc=capture('account-multipage');
    assert.equal(doc.querySelectorAll('.statement-table > tbody:first-of-type tr').length, 91);
    assert.equal(doc.querySelectorAll('.statement-totals').length, 1);
    w.eval(`db.giderler=[{id:1,tarih:'14.09.2026',kategori:'Elektrik',aciklama:'Üretim tesisi elektrik gideri',tutar:12500}];`);
    w.printList('expenses'); doc=capture('report');
    assert(doc.querySelector('.report-list-table td.number-cell'));
    dom.window.close();
    console.log('Print documents: conditional totals, references, XSS, record isolation, all six document types and multi-page ledger passed.');
})().catch(error => { console.error(error); process.exitCode = 1; });
