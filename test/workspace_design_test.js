const assert = require('node:assert/strict');
const fs = require('node:fs');
const { JSDOM } = require('jsdom');
const html = fs.readFileSync('index.html', 'utf8').replace(/<script\b[^>]*>[\s\S]*?<\/script>/gi, '');
const delay = ms => new Promise(resolve => setTimeout(resolve, ms));

(async () => {
    const dom = new JSDOM(html, { url: 'http://workspace-test.local', runScripts: 'dangerously', pretendToBeVisual: true });
    const w = dom.window;
    w.alert = () => {};
    w.confirm = () => true;
    w.console.warn = () => {};
    const script = w.document.createElement('script');
    script.textContent = fs.readFileSync('app.js', 'utf8');
    w.document.body.appendChild(script);
    await delay(100);
    const doc = w.document;
    assert.equal(doc.documentElement.dataset.theme, 'light');
    assert.equal(doc.querySelector('#nav-group-operations').hidden, false);
    w.toggleNavGroup('reports');
    assert.equal(doc.querySelector('#nav-group-operations').hidden, false, 'Opening another menu must keep existing navigation available');
    assert.equal(doc.querySelector('#nav-group-reports').hidden, false);
    w.switchView('accounts');
    assert.equal(doc.querySelector('#nav-group-reports').hidden, false, 'Navigation must preserve independently expanded groups');
    w.eval(`db.cariler = [
        {id: 701, kodu: 'C-701', adi: 'İŞIK Çelik', bakiye: 420, tel: '555'},
        {id: 702, kodu: 'C-702', adi: '<img src=x onerror=alert(1)> Malzeme', bakiye: 0}
    ]; db.isEmirleri = [{id:801, orderNo:'EMR-000801', customerId:701, customerName:'İŞIK Çelik', description:'Kesim', total:420, durum:'Beklemede', tarih:'14.09.2026'}];`);
    const before = w.eval('JSON.stringify(db)');
    w.openWorkspaceSearch();
    await delay(5);
    const input = doc.getElementById('workspace-search-input');
    input.value = 'isik celik';
    w.renderWorkspaceSearch();
    assert.equal(doc.querySelectorAll('.workspace-search-result').length, 2, 'Turkish diacritics must match account and linked order');
    input.value = 'EMR-000801';
    w.renderWorkspaceSearch();
    input.dispatchEvent(new w.KeyboardEvent('keydown', {key:'ArrowDown',bubbles:true}));
    assert.equal(doc.activeElement, doc.querySelector('.workspace-search-result'), 'Arrow keys must focus a result');
    doc.querySelector('.workspace-search-result').click();
    await delay(130);
    assert.equal(w.location.hash, '#orders');
    assert(doc.querySelector('#modal-order-history').classList.contains('active'), 'Result must open the matching record');
    assert(doc.querySelector('#modal-order-history').textContent.includes('EMR-000801'));
    assert(!doc.querySelector('#modal-workspace-search').classList.contains('active'));
    w.closeModal('modal-order-history');
    w.openWorkspaceSearch();
    input.value='Malzeme'; w.renderWorkspaceSearch();
    assert(!doc.querySelector('#workspace-search-results img'), 'Search must escape imported record names');
    assert(doc.querySelector('#workspace-search-results').textContent.includes('<img'));
    input.value='kesinlikle-eslesmeyen-kayit'; w.renderWorkspaceSearch();
    assert(doc.querySelector('.workspace-search-empty'));
    input.dispatchEvent(new w.KeyboardEvent('keydown', {key:'Escape',bubbles:true}));
    assert(!doc.querySelector('#modal-workspace-search').classList.contains('active'), 'Escape must close search without a discard dialog');
    w.openModal('modal-cari');
    doc.getElementById('input-cari-adi').value='Kaydedilmemiş bilgi';
    doc.dispatchEvent(new w.KeyboardEvent('keydown', {key:'k',ctrlKey:true,bubbles:true}));
    assert(!doc.querySelector('#modal-workspace-search').classList.contains('active'), 'Search shortcut must not replace an open form');
    w.closeModal('modal-cari');
    w.toggleWorkspaceTheme();
    w.toggleWorkspaceDensity();
    w.eval('applyWorkspacePreferences()');
    assert.equal(doc.documentElement.dataset.theme, 'dark');
    assert.equal(doc.documentElement.dataset.density, 'compact');
    assert.equal(JSON.parse(w.localStorage.getItem('AkLazerWorkspacePreferences')).density, 'compact');
    assert.equal(w.eval('JSON.stringify(db)'), before, 'Design preferences and search must never modify accounting records');
    w.eval(`db.cariler = Array.from({length:1000}, (_,i)=>({id:i,adi:'Yoğun Kayıt '+i,kodu:'C-'+i}));`);
    assert.equal(w.eval("getWorkspaceSearchItems('yogun').length"), 12, 'Large record searches must cap each source');
    assert(!w.eval("getWorkspaceSearchItems('y').some(i=>i.kind==='Cari')"), 'One-character searches must not scan records');
    w.switchView('missing-route');
    assert(doc.querySelector('#view-dashboard').classList.contains('active'));
    dom.window.close();
    console.log('Workspace design: navigation, Turkish search, record links, keyboard controls, XSS, preferences and data isolation passed.');
})().catch(error => { console.error(error); process.exitCode = 1; });
